// types/events.ts
// =============================================================================
// Hotel Poinisuk — Event types
// Shared between the public karaoke/events page and the admin dashboard.
// Mirrors the DynamoDB record shape produced by the AWS Lambda backend
// (see /aws/README.md for the full schema and deployment guide).
// =============================================================================

/**
 * Event categories — used both for filtering on the public page and for
 * picking an icon/colour treatment in the admin dashboard. Keep this list
 * tight; new categories should be added to the Lambda allow-list too.
 */
export type EventCategory =
  | "karaoke"
  | "live-music"
  | "dj-night"
  | "festival"
  | "private-event"
  | "other";

/**
 * Wire shape of an event as returned by `GET /events` and stored in
 * DynamoDB. Dates and times are kept as strings so the JSON payload stays
 * stable across timezones — the client formats them with Intl APIs.
 */
export interface EventRecord {
  /** UUID v4 generated by the backend on create. */
  id: string;
  /** Short headline shown on cards (e.g. "Saturday Night Karaoke"). */
  title: string;
  /** Optional secondary line (e.g. "feat. DJ Khasi Beats"). */
  subtitle?: string;
  /** ISO date in `YYYY-MM-DD` (local Shillong calendar date). */
  date: string;
  /** 24-hour clock `HH:mm` (e.g. "20:00"). */
  startTime: string;
  /** Optional 24-hour clock `HH:mm` (e.g. "23:30"). */
  endTime?: string;
  /** 1-3 paragraphs of event copy, plain text. */
  description: string;
  /** Optional public S3 URL for the event image (uploaded via presigned URL). */
  imageUrl?: string;
  /** One of the `EventCategory` slugs. Defaults to `karaoke` on the backend. */
  category: EventCategory;
  /** Highlighted events float to the top of the public listing. */
  isHighlighted?: boolean;
  /**
   * When true and the event date is in the past, the event appears in the
   * "Previous events" strip on the karaoke page (same card style as upcoming).
   */
  showInPastHighlights?: boolean;
  /** Optional cover charge / entry fee, plain string ("Free Entry", "₹500"). */
  cover?: string;
  /** ISO timestamp set by the backend on create. */
  createdAt: string;
  /** ISO timestamp updated by the backend on every PUT. */
  updatedAt?: string;
}

/**
 * Payload shape for create/update. The backend stamps `id`, `createdAt`,
 * and `updatedAt` so we don't include them here.
 */
export interface EventInput {
  title: string;
  subtitle?: string;
  date: string;
  startTime: string;
  endTime?: string;
  description: string;
  imageUrl?: string;
  category: EventCategory;
  isHighlighted?: boolean;
  showInPastHighlights?: boolean;
  cover?: string;
}

/**
 * Friendly labels for each category — used in the admin dropdown and the
 * public chips. Centralised so we never drift between pages.
 */
export const EVENT_CATEGORY_LABELS: Record<EventCategory, string> = {
  karaoke: "Karaoke Night",
  "live-music": "Live Music",
  "dj-night": "DJ Night",
  festival: "Festival",
  "private-event": "Private Event",
  other: "Other",
};

/**
 * Lightweight client-side validation. Mirrors the rules enforced by the
 * Lambda — keeps the admin UX snappy by failing fast before the round-trip.
 */
export function validateEventInput(input: EventInput): string | null {
  if (!input.title?.trim()) return "Please enter an event title.";
  if (!input.date?.trim()) return "Please pick a date for the event.";
  if (!/^\d{4}-\d{2}-\d{2}$/.test(input.date))
    return "Date must be in YYYY-MM-DD format.";
  if (!input.startTime?.trim()) return "Please set a start time.";
  if (!/^\d{2}:\d{2}$/.test(input.startTime))
    return "Start time must be in HH:mm format.";
  if (input.endTime && !/^\d{2}:\d{2}$/.test(input.endTime))
    return "End time must be in HH:mm format.";
  if (!input.description?.trim())
    return "Please add a short description for the event.";
  if (!input.category) return "Please choose an event category.";
  return null;
}
